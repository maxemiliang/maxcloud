// Command gendocs writes the generated reference in docs/reference: the
// mcloud commands (from their help), maxcloud.yaml (from
// maxcloud.schema.json) and the controller's custom resources (from the
// CRDs controller-gen writes). Run it from the repository's root:
//
//	go run ./internal/gendocs
//
// CI runs it and fails if docs/reference changes.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
	"sigs.k8s.io/yaml"

	"github.com/maxemiliang/maxcloud/internal/cli"
)

const (
	outDir    = "docs/reference"
	schema    = "maxcloud.schema.json"
	crdDir    = "controller/config/crd"
	generated = "<!-- Generated by `go run ./internal/gendocs`: edit the source it names, not this file. -->\n\n"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gendocs:", err)
		os.Exit(1)
	}
}

func run() error {
	if _, err := os.Stat(schema); err != nil {
		return fmt.Errorf("run this from the repository's root: %w", err)
	}
	// Start from nothing, so a removed command's page goes too.
	if err := os.RemoveAll(outDir); err != nil {
		return err
	}
	files := map[string]string{}
	cliDocs(cli.New(), files)
	if err := schemaDoc(files); err != nil {
		return err
	}
	if err := crdDoc(files); err != nil {
		return err
	}
	for name, content := range files {
		path := filepath.Join(outDir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// --- mcloud ---

func cliDocs(root *cobra.Command, files map[string]string) {
	var b strings.Builder
	b.WriteString("# mcloud\n\n")
	b.WriteString(generatedFrom("the commands' help in `internal/cli`"))
	b.WriteString(prose(root.Long) + "\n\n")
	b.WriteString("## Commands\n\n")
	b.WriteString("| Command | |\n| --- | --- |\n")
	for _, c := range commands(root) {
		fmt.Fprintf(&b, "| [`%s`](%s) | %s |\n", c.CommandPath(), pageName(c), cell(c.Short))
	}
	b.WriteString("\n## Global flags\n\nEvery command takes these.\n\n")
	b.WriteString(flagTable(root.PersistentFlags()))
	files["cli/README.md"] = b.String()

	for _, c := range commands(root) {
		var b strings.Builder
		fmt.Fprintf(&b, "# %s\n\n", c.CommandPath())
		b.WriteString(generatedFrom("the command's help in `internal/cli`"))
		b.WriteString("[All commands](README.md)\n\n")
		command(&b, c)
		for _, sub := range descendants(c) {
			fmt.Fprintf(&b, "## %s\n\n", sub.CommandPath())
			command(&b, sub)
		}
		files["cli/"+pageName(c)] = b.String()
	}
}

// command writes one command's help, under a heading the caller wrote.
func command(b *strings.Builder, c *cobra.Command) {
	b.WriteString(prose(c.Short) + ".\n\n")
	if c.Long != "" {
		b.WriteString(prose(c.Long) + "\n\n")
	}
	if c.Runnable() {
		fmt.Fprintf(b, "```\n%s\n```\n\n", c.UseLine())
	}
	if subs := commands(c); len(subs) > 0 {
		b.WriteString("| Command | |\n| --- | --- |\n")
		for _, s := range subs {
			fmt.Fprintf(b, "| [`%s`](#%s) | %s |\n", s.CommandPath(), anchor(s.CommandPath()), cell(s.Short))
		}
		b.WriteString("\n")
	}
	if c.Example != "" {
		ex := strings.Split(strings.TrimRight(c.Example, "\n"), "\n")
		for i, l := range ex {
			ex[i] = strings.TrimPrefix(l, "  ")
		}
		fmt.Fprintf(b, "Examples:\n\n```fish\n%s\n```\n\n", strings.Join(ex, "\n"))
	}
	if t := flagTable(c.NonInheritedFlags()); t != "" {
		b.WriteString("Flags:\n\n" + t)
	}
}

// commands are c's documented subcommands: not hidden, not help or
// completion.
func commands(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range c.Commands() {
		if !s.IsAvailableCommand() || s.IsAdditionalHelpTopicCommand() || s.Name() == "help" || s.Name() == "completion" {
			continue
		}
		out = append(out, s)
	}
	return out
}

// descendants are c's subcommands at every depth, depth first.
func descendants(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range commands(c) {
		out = append(out, s)
		out = append(out, descendants(s)...)
	}
	return out
}

func pageName(c *cobra.Command) string {
	return strings.ReplaceAll(c.CommandPath(), " ", "-") + ".md"
}

// anchor is GitHub's anchor for a heading of plain words.
func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), " ", "-")
}

func flagTable(fs *pflag.FlagSet) string {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "`--" + f.Name + "`"
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		typ, usage := pflag.UnquoteUsage(f)
		if typ != "" {
			name += " " + typ
		}
		def := ""
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "[]" && f.DefValue != "0" {
			def = "`" + f.DefValue + "`"
		}
		rows = append(rows, fmt.Sprintf("| %s | %s | %s |", name, def, cell(usage)))
	})
	if len(rows) == 0 {
		return ""
	}
	return "| Flag | Default | |\n| --- | --- | --- |\n" + strings.Join(rows, "\n") + "\n\n"
}

// --- maxcloud.yaml ---

// jsonSchema is the part of JSON Schema maxcloud.schema.json uses.
type jsonSchema struct {
	Description string        `json:"description"`
	Type        any           `json:"type"`
	Required    []string      `json:"required"`
	Properties  orderedProps  `json:"properties"`
	Items       *jsonSchema   `json:"items"`
	OneOf       []*jsonSchema `json:"oneOf"`
	Enum        []any         `json:"enum"`
	Default     any           `json:"default"`
	Examples    []any         `json:"examples"`
}

func schemaDoc(files map[string]string) error {
	data, err := os.ReadFile(schema)
	if err != nil {
		return err
	}
	var s jsonSchema
	if err := json.Unmarshal(data, &s); err != nil {
		return fmt.Errorf("%s: %w", schema, err)
	}
	var b strings.Builder
	b.WriteString("# maxcloud.yaml\n\n")
	b.WriteString(generatedFrom("[`maxcloud.schema.json`](../../maxcloud.schema.json)"))
	b.WriteString(prose(s.Description) + " What each field is for: [maxcloud.yaml](../maxcloud-yaml.md).\n\n")
	b.WriteString("For completion and checking in an editor with the YAML language server, start the file with:\n\n")
	b.WriteString("```yaml\n# yaml-language-server: $schema=https://raw.githubusercontent.com/maxemiliang/maxcloud/main/maxcloud.schema.json\n```\n\n")
	b.WriteString("| Field | Type | Default | |\n| --- | --- | --- | --- |\n")
	schemaRows(&b, "", &s)
	b.WriteString("\n")
	files["maxcloud-yaml.md"] = b.String()
	return nil
}

func schemaRows(b *strings.Builder, prefix string, s *jsonSchema) {
	for _, prop := range s.Properties {
		name, p := prop.name, prop.schema
		path := prefix + name
		typ := schemaType(p)
		if slices.Contains(s.Required, name) {
			typ += ", required"
		}
		def := ""
		if p.Default != nil {
			def = "`" + fmt.Sprint(p.Default) + "`"
		}
		desc := cell(p.Description)
		examples := p.Examples
		if p.Items != nil {
			examples = append(examples, p.Items.Examples...)
		}
		if len(examples) > 0 {
			var ex []string
			for _, e := range examples {
				ex = append(ex, "`"+fmt.Sprint(e)+"`")
			}
			desc += " E.g. " + strings.Join(ex, ", ")
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", path, typ, def, desc)
		switch {
		case p.Properties != nil:
			schemaRows(b, path+".", p)
		case p.Items != nil && p.Items.Properties != nil:
			schemaRows(b, path+"[].", p.Items)
		}
		for _, alt := range p.OneOf {
			if alt.Properties != nil {
				schemaRows(b, path+".", alt)
			}
		}
	}
}

// orderedProps keeps a schema's properties in the file's order: the order
// the reference lists them in.
type orderedProps []struct {
	name   string
	schema *jsonSchema
}

func (o *orderedProps) UnmarshalJSON(data []byte) error {
	d := json.NewDecoder(strings.NewReader(string(data)))
	if _, err := d.Token(); err != nil { // {
		return err
	}
	for d.More() {
		t, err := d.Token()
		if err != nil {
			return err
		}
		var s jsonSchema
		if err := d.Decode(&s); err != nil {
			return err
		}
		*o = append(*o, struct {
			name   string
			schema *jsonSchema
		}{t.(string), &s})
	}
	return nil
}

func schemaType(s *jsonSchema) string {
	if len(s.OneOf) > 0 {
		var ts []string
		for _, alt := range s.OneOf {
			ts = append(ts, schemaType(alt))
		}
		return strings.Join(ts, " or ")
	}
	var t string
	switch v := s.Type.(type) {
	case string:
		t = v
	case []any:
		var ts []string
		for _, x := range v {
			ts = append(ts, fmt.Sprint(x))
		}
		t = strings.Join(ts, " or ")
	}
	if t == "array" && s.Items != nil {
		t = "list of " + schemaType(s.Items) + "s"
	}
	if len(s.Enum) > 0 {
		var es []string
		for _, e := range s.Enum {
			// 1 and "1" are the same value to mcloud: list it once.
			if v := fmt.Sprint(e); !slices.Contains(es, v) {
				es = append(es, v)
			}
		}
		t += ": " + strings.Join(es, ", ")
	}
	return t
}

// --- custom resources ---

type crd struct {
	Spec struct {
		Group string `json:"group"`
		Names struct {
			Kind       string   `json:"kind"`
			Plural     string   `json:"plural"`
			ShortNames []string `json:"shortNames"`
		} `json:"names"`
		Versions []struct {
			Name   string `json:"name"`
			Schema struct {
				OpenAPIV3Schema *openAPI `json:"openAPIV3Schema"`
			} `json:"schema"`
		} `json:"versions"`
	} `json:"spec"`
}

type openAPI struct {
	Description string              `json:"description"`
	Type        string              `json:"type"`
	Format      string              `json:"format"`
	Required    []string            `json:"required"`
	Properties  map[string]*openAPI `json:"properties"`
	Items       *openAPI            `json:"items"`
	Enum        []any               `json:"enum"`
	Default     any                 `json:"default"`
	Pattern     string              `json:"pattern"`
}

func crdDoc(files map[string]string) error {
	paths, err := filepath.Glob(filepath.Join(crdDir, "*.yaml"))
	if err != nil {
		return err
	}
	var crds []crd
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		var c crd
		if err := yaml.Unmarshal(data, &c); err != nil {
			return fmt.Errorf("%s: %w", p, err)
		}
		crds = append(crds, c)
	}
	sort.Slice(crds, func(i, j int) bool { return crds[i].Spec.Names.Kind < crds[j].Spec.Names.Kind })

	var b strings.Builder
	b.WriteString("# Custom resources\n\n")
	b.WriteString(generatedFrom("the types in [`controller/api`](../../controller/api), through controller-gen's CRDs"))
	b.WriteString("What the maxcloud controller works from. The app registry creates Buckets, Databases and Domains from an app's entry (apps can read them, not change them); apps may create DatabaseBranches. `kubectl get maxcloud -n <app>` lists them all. How the controller acts on them: [controller/README.md](../../controller/README.md).\n\n")
	for _, c := range crds {
		fmt.Fprintf(&b, "- [%s](#%s)\n", c.Spec.Names.Kind, strings.ToLower(c.Spec.Names.Kind))
	}
	b.WriteString("\n")
	for _, c := range crds {
		for _, v := range c.Spec.Versions {
			s := v.Schema.OpenAPIV3Schema
			if s == nil {
				continue
			}
			fmt.Fprintf(&b, "## %s\n\n", c.Spec.Names.Kind)
			fmt.Fprintf(&b, "`apiVersion: %s/%s`, `kubectl get %s`\n\n", c.Spec.Group, v.Name, c.Spec.Names.Plural)
			b.WriteString(prose(s.Description) + "\n\n")
			for _, part := range []string{"spec", "status"} {
				p := s.Properties[part]
				if p == nil || len(p.Properties) == 0 {
					continue
				}
				fmt.Fprintf(&b, "### %s\n\n", part)
				b.WriteString("| Field | Type | Default | |\n| --- | --- | --- | --- |\n")
				crdRows(&b, "", p)
				b.WriteString("\n")
			}
		}
	}
	files["crds.md"] = b.String()
	return nil
}

func crdRows(b *strings.Builder, prefix string, s *openAPI) {
	for _, name := range sortedKeys(s.Properties) {
		p := s.Properties[name]
		path := prefix + name
		typ := p.Type
		if p.Format != "" {
			typ += " (" + p.Format + ")"
		}
		if p.Type == "array" && p.Items != nil {
			typ = "list"
			if name == "conditions" {
				typ = "list of conditions"
			}
		}
		if len(p.Enum) > 0 {
			var es []string
			for _, e := range p.Enum {
				es = append(es, fmt.Sprint(e))
			}
			typ += ": " + strings.Join(es, ", ")
		}
		if slices.Contains(s.Required, name) {
			typ += ", required"
		}
		def := ""
		if p.Default != nil {
			def = "`" + fmt.Sprint(p.Default) + "`"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n", path, typ, def, cell(p.Description))
		// Conditions are the standard metav1.Condition: not worth a row each.
		if name == "conditions" {
			continue
		}
		switch {
		case len(p.Properties) > 0:
			crdRows(b, path+".", p)
		case p.Items != nil && len(p.Items.Properties) > 0:
			crdRows(b, path+"[].", p.Items)
		}
	}
}

// --- Markdown ---

func generatedFrom(source string) string {
	return generated + "_Generated from " + source + "._\n\n"
}

// mdEscaper keeps help text from turning into Markdown it never meant:
// <app> into an HTML tag, mc-*--* into emphasis.
var mdEscaper = strings.NewReplacer(
	`\`, `\\`, "`", "\\`", `*`, `\*`, `_`, `\_`, `<`, `&lt;`, `>`, `&gt;`, `[`, `\[`, `]`, `\]`,
)

// prose is help text as Markdown paragraphs: lines joined as written,
// blank lines between paragraphs kept, lines starting "- " kept as lists.
func prose(s string) string {
	return mdEscaper.Replace(strings.TrimSpace(s))
}

// cell is text for a table cell: one line, pipes escaped.
func cell(s string) string {
	s = strings.TrimSpace(s)
	s = strings.ReplaceAll(s, "\n\n", "<br><br>")
	parts := strings.Split(s, "<br><br>")
	for i, p := range parts {
		parts[i] = mdEscaper.Replace(strings.Join(strings.Fields(p), " "))
	}
	return strings.ReplaceAll(strings.Join(parts, "<br><br>"), "|", `\|`)
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
