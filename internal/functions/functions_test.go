func docs(t *testing.T, data []byte) map[string]map[string]any {
	t.Helper()
	out := map[string]map[string]any{}
	for _, part := range strings.Split(string(data), "\n---\n") {
		var m map[string]any
		if err := yaml.Unmarshal([]byte(part), &m); err != nil {
			t.Fatal(err)
		}
		if m == nil {
			continue
		}
		meta := m["metadata"].(map[string]any)
		out[m["kind"].(string)+"/"+meta["name"].(string)] = m
	}
	return out
}

func get(m any, path ...any) any {
	for _, p := range path {
		switch k := p.(type) {
		case string:
			m = m.(map[string]any)[k]
		case int:
			m = m.([]any)[k]
		}
	}
	return m
}

func TestParseTaggedOutput(t *testing.T) {
	out := "> app@1.0.0 start\n> maxcloud-functions\n\nsome log line\n" + DescribeTag + strings.ReplaceAll(desc, "\n", "") + "\n"
	d, err := Parse([]byte(out))
	if err != nil {
		t.Fatal(err)
	}
	if len(d.Functions) != 3 || !d.NeedsDatabase() {
		t.Fatalf("%+v", d)
	}
	if _, err := Parse([]byte("just logs\n")); err == nil {
		t.Error("want an error without a description")
	}
}

func TestParseRejects(t *testing.T) {
	for _, bad := range []string{
		`{"functions":[{"name":"x","kind":"http","timeoutSeconds":900}]}`,
		`{"functions":[{"name":"x","kind":"schedule","schedule":"daily"}]}`,
		`{"functions":[{"name":"x","kind":"teleport"}]}`,
		`{"functions":[{"name":"Bad_Name","kind":"http"}]}`,
		`{"functions":[{"name":"x","kind":"http"},{"name":"x","kind":"http"}]}`,
	} {
		if _, err := Parse([]byte(bad)); err == nil {
			t.Errorf("%s: want an error", bad)
		}
	}
}

func TestManifests(t *testing.T) {
	d, err := Parse([]byte(desc))
	if err != nil {
		t.Fatal(err)
	}
	out, err := Manifests(d, Options{LegacyDatabase: true})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(out), "# Generated by mcloud") {
		t.Error("no header")
	}
	m := docs(t, out)

	ksvc := m["Service/api"]
	if get(ksvc, "metadata", "labels", "run.gronblom.dev/expose") != "public" {
		t.Error("api should be public")
	}
	spec := get(ksvc, "spec", "template", "spec")
	if get(spec, "priorityClassName") != "tenant" || get(spec, "containerConcurrency") != float64(10) {
		t.Errorf("ksvc spec %v", spec)
	}
	c := get(spec, "containers", 0)
	if get(c, "image") != "app" || get(c, "env", 0, "value") != "api" || get(c, "env", 1, "name") != "DATABASE_URL" {
		t.Errorf("container %v", c)
	}
	if get(c, "resources", "limits", "memory") != "256Mi" {
		t.Errorf("resources %v", get(c, "resources"))
	}

	cj := m["CronJob/nightly"]
	if get(cj, "spec", "timeZone") != "Europe/Helsinki" || get(cj, "spec", "jobTemplate", "spec", "backoffLimit") != float64(1) {
		t.Errorf("cronjob %v", get(cj, "spec"))
	}
	if get(cj, "spec", "jobTemplate", "spec", "template", "spec", "securityContext", "runAsNonRoot") != true {
		t.Error("cronjob pods must be restricted")
	}

	dep := m["Deployment/resize"]
	if _, ok := get(dep, "spec").(map[string]any)["replicas"]; ok {
		t.Error("the worker Deployment must leave replicas to KEDA")
	}
	so := m["ScaledObject/resize"]
	if get(so, "spec", "maxReplicaCount") != float64(4) || get(so, "spec", "triggers", 0, "metadata", "targetQueryValue") != "2" {
		t.Errorf("scaledobject %v", get(so, "spec"))
	}
}

// Without database.yaml, DATABASE_URL is optional: the app may have a
// database from the registry instead, or none. With it, it's required.
// Every function also gets the app's bucket credentials, if it has any.
func TestManifestsOptionalStorage(t *testing.T) {
	d, err := Parse([]byte(desc))
	if err != nil {
		t.Fatal(err)
	}
	for _, withDB := range []bool{false, true} {
		out, err := Manifests(d, Options{LegacyDatabase: withDB})
		if err != nil {
			t.Fatal(err)
		}
		c := get(docs(t, out)["Service/api"], "spec", "template", "spec", "containers", 0)
		if get(c, "env", 1, "name") != "DATABASE_URL" {
			t.Fatalf("env %v", get(c, "env"))
		}
		optional := get(c, "env", 1, "valueFrom", "secretKeyRef", "optional")
		if withDB && optional != nil {
			t.Errorf("with database.yaml, DATABASE_URL should be required, got optional=%v", optional)
		}
		if !withDB && optional != true {
			t.Errorf("without database.yaml, DATABASE_URL should be optional, got %v", optional)
		}
		if get(c, "envFrom", 0, "secretRef", "name") != StorageSecret || get(c, "envFrom", 0, "secretRef", "optional") != true {
			t.Errorf("envFrom %v", get(c, "envFrom"))
		}
	}
}

func TestWriteDir(t *testing.T) {
	d, _ := Parse([]byte(desc))
	dir := filepath.Join(t.TempDir(), "deploy", "k8s")
	changed, err := WriteDir(dir, d, "")
	if err != nil {
		t.Fatal(err)
	}
	if len(changed) != 2 {
		t.Errorf("changed %v (want functions.yaml and kustomization.yaml)", changed)
	}
	// No database.yaml any more: the database comes from the registry.
	if _, err := os.Stat(filepath.Join(dir, LegacyDatabaseFile)); err == nil {
		t.Error("wrote database.yaml")
	}
	k, _ := os.ReadFile(filepath.Join(dir, "kustomization.yaml"))
	for _, want := range []string{"  - functions.yaml\n", "images:\n  - name: app\n"} {
		if !strings.Contains(string(k), want) {
			t.Errorf("kustomization lacks %q:\n%s", want, k)
		}
	}
	if strings.Contains(string(k), "database.yaml") {
		t.Errorf("kustomization lists database.yaml:\n%s", k)
	}
	// The queue's KEDA login is in functions.yaml now.
	f, _ := os.ReadFile(filepath.Join(dir, "functions.yaml"))
	if !strings.Contains(string(f), "kind: TriggerAuthentication") {
		t.Errorf("functions.yaml has no TriggerAuthentication:\n%s", f)
	}
	// Second run: nothing changes.
	if changed, err := WriteDir(dir, d, ""); err != nil || len(changed) != 0 {
		t.Errorf("rerun changed %v, %v", changed, err)
	}
	// After `kustomize edit set image` (unindented lists), a rerun still
	// sees what's listed.
	os.WriteFile(filepath.Join(dir, "kustomization.yaml"), []byte("apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n- functions.yaml\nimages:\n- digest: sha256:abc\n  name: app\n  newName: ghcr.io/o/r\n"), 0o644)
	if changed, err := WriteDir(dir, d, ""); err != nil || len(changed) != 0 {
		t.Errorf("after kustomize edit: changed %v, %v", changed, err)
	}
	// The user's own manifests stay listed, and an existing images block isn't duplicated.
	os.WriteFile(filepath.Join(dir, "kustomization.yaml"), []byte("apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - sso.yaml\nimages:\n  - name: app\n    newName: ghcr.io/o/r\n    digest: sha256:abc\n"), 0o644)
	if _, err := WriteDir(dir, d, ""); err != nil {
		t.Fatal(err)
	}
	k, _ = os.ReadFile(filepath.Join(dir, "kustomization.yaml"))
	if !strings.Contains(string(k), "  - sso.yaml\n") || strings.Count(string(k), "images:") != 1 || !strings.Contains(string(k), "digest: sha256:abc") {
		t.Errorf("kustomization:\n%s", k)
	}
}

// An app that already has a database.yaml keeps it: it stays listed, and
// functions.yaml doesn't define a second TriggerAuthentication db.
func TestWriteDirKeepsALegacyDatabase(t *testing.T) {
	d, _ := Parse([]byte(desc))
	dir := filepath.Join(t.TempDir(), "deploy", "k8s")
	os.MkdirAll(dir, 0o755)
	os.WriteFile(filepath.Join(dir, LegacyDatabaseFile), []byte("# mine\n"), 0o644)
	if _, err := WriteDir(dir, d, ""); err != nil {
		t.Fatal(err)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, LegacyDatabaseFile)); string(b) != "# mine\n" {
		t.Errorf("database.yaml changed: %q", b)
	}
	k, _ := os.ReadFile(filepath.Join(dir, "kustomization.yaml"))
	if !strings.Contains(string(k), "  - database.yaml\n  - functions.yaml\n") {
		t.Errorf("kustomization:\n%s", k)
	}
	f, _ := os.ReadFile(filepath.Join(dir, "functions.yaml"))
	if strings.Contains(string(f), "kind: TriggerAuthentication") {
		t.Error("a second TriggerAuthentication db next to database.yaml's")
	}
}

