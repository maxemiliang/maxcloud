const desc = `{"sdk":"@max-cloud/functions","version":"0.1.0","functions":[
 {"name":"api","export":"api","kind":"http","memory":"256Mi","cpu":null,"public":true,"minInstances":0,"maxInstances":3,"concurrency":10,"timeoutSeconds":300},
 {"name":"nightly","export":"nightly","kind":"schedule","memory":null,"cpu":null,"schedule":"0 3 * * *","timeZone":"Europe/Helsinki","retries":1,"timeoutSeconds":600},
 {"name":"resize","export":"resize","kind":"queue","memory":null,"cpu":"50m","queue":"images","concurrency":2,"maxInstances":4,"maxAttempts":5,"backoffSeconds":10,"timeoutSeconds":0.5,"backlogQuery":"SELECT count(*) FROM maxcloud_jobs WHERE queue = 'images'"}]}`

func docs(t *testing.T, data []byte) map[string]map[string]any {
	t.Helper()
	out := map[string]map[string]any{}
	for _, part := range strings.Split(string(data), "\n---\n") {
		var m map[string]any
		if err := yaml.Unmarshal([]byte(part), &m); err != nil {
			t.Fatal(err)
		}
		if m == nil {
			continue
		}
		meta := m["metadata"].(map[string]any)
		out[m["kind"].(string)+"/"+meta["name"].(string)] = m
	}
	return out
}

func get(m any, path ...any) any {
	for _, p := range path {
		switch k := p.(type) {
		case string:
			m = m.(map[string]any)[k]
		case int:
			m = m.([]any)[k]
		}
	}
	return m
}

func TestParseTaggedOutput(t *testing.T) {
	out := "> app@1.0.0 start\n> maxcloud-functions\n\nsome log line\n" + DescribeTag + strings.ReplaceAll(desc, "\n", "") + "\n"
	d, err := Parse([]byte(out))
	if err != nil {
		t.Fatal(err)
	}
	if len(d.Functions) != 3 || !d.NeedsDatabase() {
		t.Fatalf("%+v", d)
	}
	if _, err := Parse([]byte("just logs\n")); err == nil {
		t.Error("want an error without a description")
	}
}

