#!/usr/bin/env bash
# Regenerates infrastructure/controllers/traefik/cloudflare-ips.yaml (a Helm
# values fragment for Traefik) from Cloudflare's published edge IP ranges.
# Run weekly by the repo's .github/workflows/cloudflare-ips.yaml; safe to run locally.
set -euo pipefail
cd "$(dirname "$0")/.."

out="infrastructure/controllers/traefik/cloudflare-ips.yaml"
json=$(curl -fsS --retry 3 --max-time 30 https://api.cloudflare.com/client/v4/ips)

# Refuse to write an empty or unexpected list: every entry must look like a CIDR.
cidrs=$(jq -er '
  if .success != true then error("API call failed") else . end
  | .result.ipv4_cidrs + .result.ipv6_cidrs
  | if length > 0 and all(test("^[0-9a-f.:]+/[0-9]{1,3}$"))
    then .[] else error("unexpected IP list") end
' <<<"$json")

{
  echo "# Generated by scripts/update-cloudflare-ips.sh from"
  echo "# https://api.cloudflare.com/client/v4/ips. Do not edit by hand."
  echo "#"
  echo "# Requests arriving from these addresses keep their X-Forwarded-* headers, so"
  echo "# Traefik's access log and the apps see the real client IP on proxied hosts."
  echo "ports:"
  echo "  websecure:"
  echo "    forwardedHeaders:"
  echo "      trustedIPs:"
  while read -r cidr; do
    echo "        - $cidr"
  done <<<"$cidrs"
} >"$out"
